import sys
import math

# Предельное значение коэффициентов (по модулю)
MAX_VALUE = 10000

HELP_TEXT = """mathtool — решение уравнений вида A*x^2 + B*x + C = 0

Использование:
    python mathtool.py                         вывод справки
    python mathtool.py --help                  вывод справки
    python mathtool.py solve                   ввод коэффициентов с клавиатуры
    python mathtool.py solve -a 1 -b -3 -c 2   решение с заданными коэффициентами

Коэффициенты A, B, C — целые числа, по модулю не превышающие 10000."""


# ---------------------------------------------------------------
# Блок 1. Разбор параметров командной строки
# ---------------------------------------------------------------
# sys.argv[0] — имя программы, дальше идут параметры.
# Количество параметров = len(sys.argv) - 1
args_count = len(sys.argv) - 1

# Параметров нет или первый параметр --help -> справка, код 0
if args_count == 0 or sys.argv[1] == "--help":
    print(HELP_TEXT)
    sys.exit(0)

# Первый параметр не solve -> неизвестная команда, код 1
if sys.argv[1] != "solve":
    print("ОШИБКА: неизвестная команда", file=sys.stderr)
    sys.exit(1)

# Дальше работаем только с командой solve.
# Строки с коэффициентами складываем в переменные a_text, b_text, c_text.
if args_count == 1:
    # Только solve -> запрашиваем коэффициенты с клавиатуры
    a_text = input("Введите A: ")
    b_text = input("Введите B: ")
    c_text = input("Введите C: ")
elif args_count == 7:
    # solve -a .. -b .. -c .. -> проверяем, что имена параметров верные
    if sys.argv[2] != "-a" or sys.argv[4] != "-b" or sys.argv[6] != "-c":
        print("ОШИБКА: неизвестный параметр", file=sys.stderr)
        sys.exit(1)
    a_text = sys.argv[3]
    b_text = sys.argv[5]
    c_text = sys.argv[7]
else:
    print("ОШИБКА: неверный набор параметров", file=sys.stderr)
    sys.exit(1)


# ---------------------------------------------------------------
# Блок 2. Преобразование исходных данных в целые числа
# ---------------------------------------------------------------
# Строку вроде "abc" нельзя превратить в число — int() вызовет ValueError.
# try/except перехватывает эту ошибку, и программа не "падает".
try:
    a = int(a_text)
    b = int(b_text)
    c = int(c_text)
except ValueError:
    print("ОШИБКА: коэффициент не является целым числом", file=sys.stderr)
    sys.exit(1)


# ---------------------------------------------------------------
# Блок 3. Проверка значений на допустимый диапазон
# ---------------------------------------------------------------
if abs(a) > MAX_VALUE or abs(b) > MAX_VALUE or abs(c) > MAX_VALUE:
    print("ОШИБКА: значение вне допустимого диапазона", file=sys.stderr)
    sys.exit(1)


# ---------------------------------------------------------------
# Блок 4. Решение уравнения и вывод результата
# ---------------------------------------------------------------
if a != 0:
    # Квадратное уравнение
    print("Уравнение квадратное")

    d = b * b - 4 * a * c  # дискриминант
    print(f"D = {d}")

    # Знак D проверяем ДО извлечения корня: sqrt от отрицательного — ошибка
    if d > 0:
        x1 = (-b + math.sqrt(d)) / (2 * a)
        x2 = (-b - math.sqrt(d)) / (2 * a)
        print(f"x1 = {x1:.3f}")
        print(f"x2 = {x2:.3f}")
    elif d == 0:
        x = -b / (2 * a) + 0.0  # "+ 0.0" убирает неприятный вывод -0.000
        print(f"x = {x:.3f}")
    else:
        print("Действительных корней нет")
elif b != 0:
    # A = 0, B != 0 -> линейное уравнение B*x + C = 0
    print("Уравнение линейное")
    x = -c / b + 0.0
    print(f"x = {x:.3f}")
else:
    # A = 0 и B = 0 -> неизвестного нет, это не уравнение
    print("ОШИБКА: это не уравнение, неизвестное отсутствует", file=sys.stderr)
    sys.exit(1)
